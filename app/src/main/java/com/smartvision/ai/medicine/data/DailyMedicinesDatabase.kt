    private fun createMed(
        name: String,
        brand: String,
        generic: String,
        composition: String,
        category: String,
        type: MedicineType,
        dosage: String,
        food: String,
        howTo: String,
        uses: List<String>,
        sideEffects: List<String>,
        severities: Map<String, String>,
        warnings: List<String>,
        avoid: List<String>,
        interactions: List<String>,
        rx: Boolean,
        score: Int,
        level: SafetyLevel,
        emergencyWarning: String? = null,
        summary: String,
        typeOverride: MedicineType? = null
    ): MedicineInfo {
        return MedicineInfo(
            id = "db_item_" + name.replace(" ", "_").lowercase(),
            name = name,
            brandName = brand,
            genericName = generic,
            composition = composition,
            category = category,
            medicineType = typeOverride ?: type,
            dosage = dosage,
            frequency = "As prescribed",
            ageGroup = "Adults 18+",
            beforeOrAfterFood = food,
            howToUse = howTo,
            uses = uses,
            sideEffects = sideEffects,
            sideEffectSeverities = severities,
            warnings = warnings,
            whoShouldAvoid = avoid,
            interactions = interactions,
            prescriptionOnly = rx,
            safetyScore = score,
            safetyLevel = level,
            emergencyWarning = emergencyWarning,
            aiSummary = summary,
            storageInfo = "Store below 25°C in a dry place. Keep out of reach of children.",
            confidenceScore = 100,
            disclaimer = "⚕️ Medical information is generated for educational purposes only. Always consult a certified doctor or pharmacist."
        )
    }
